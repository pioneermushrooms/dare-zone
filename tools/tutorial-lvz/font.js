const cache = new Map();
/** A character's cell as W*H 0/1 values, row by row. Characters outside 32-126 draw as '?'. */
function glyph(ch) {
  if (!(ch in G)) ch = "?";
  if (cache.has(ch)) return cache.get(ch);
  const bits = new Array(W * H).fill(0);
  G[ch].split("/").forEach((row, y) => [...row].forEach((c, x) => { if (c === "#") bits[(TOP + y) * W + LEFT + x] = 1; }));
  cache.set(ch, bits);
  return bits;
}

/** Word-wrap to lines of at most maxChars; a word longer than a line is split. */
function wrap(text, maxChars) {
  const out = [];
  let line = "";
  for (let word of text.split(/\s+/).filter(Boolean)) {
    while (word.length > maxChars) {
      if (line) { out.push(line); line = ""; }
      out.push(word.slice(0, maxChars));
      word = word.slice(maxChars);
    }
    if (!line) line = word;
    else if (line.length + 1 + word.length <= maxChars) line += " " + word;
    else { out.push(line); line = word; }
  }
  if (line) out.push(line);
  return out;
}

/** Draw text with set(x, y) for each ink pixel, the first cell's top-left at (x0, y0). */
function draw(text, x0, y0, set) {
  [...text].forEach((ch, i) => {
    const bits = glyph(ch);
    for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (bits[y * W + x]) set(x0 + i * W + x, y0 + y);
  });
}

