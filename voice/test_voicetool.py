import json
import subprocess
from pathlib import Path

from voicetool import FINISH, MONSTER, drop_picks, duration, exaggeration, ffmpeg, rust_table, too_long


def test_too_long_scales_with_words():
    assert not too_long("Bombs!", 0.9)
    assert too_long("Bombs!", 2.5)
    assert not too_long("Is that the best you can do?", 1.6)
    assert too_long("Is that the best you can do?", 4.1)


def test_exaggeration_by_delivery():
    assert (exaggeration("urgent"), exaggeration("hype"), exaggeration("smug"), exaggeration("calm")) == (1.0, 1.0, 0.9, 0.6)


def test_rust_table_lists_menus_and_phrases():
    src = rust_table({"menus": [{"code": "g", "label": "Global"}],
                      "phrases": [{"code": "gw", "sound": 135, "scope": "global", "label": "Woohoo!",
                                   "text": "Woohoo!", "delivery": "hype"}]})
    assert 'VoiceMenuDef { code: "g", label: "Global" }' in src
    assert 'VoicePhraseDef { code: "gw", sound: 135, team: false, label: "Woohoo!" }' in src
    assert src.startswith("// Generated by the voice clip tooling")


def test_rust_table_escapes_quotes_and_handles_the_real_table():
    src = rust_table({"menus": [{"code": "t", "label": "Target"}],
                      "phrases": [{"code": "tq", "sound": 200, "scope": "team", "label": 'Say "hi"',
                                   "text": "x", "delivery": "calm"}]})
    assert r'label: "Say \"hi\""' in src and "team: true" in src
    real = json.loads((Path(__file__).parent / "phrases.json").read_text())
    assert rust_table(real).count("VoicePhraseDef {") == len(real["phrases"]) + 1  # +1: the struct definition


def test_monster_is_the_approved_chain():
    assert MONSTER.startswith("asetrate=24000*0.72,aresample=24000,atempo=1.3889,")
    assert "lowpass=f=3600" in MONSTER


def test_regenerating_a_phrase_forgets_its_pick():
    assert drop_picks({"gw": 2, "tr": 1, "ml": 0}, {"gw", "ml"}) == {"tr": 1}
    assert drop_picks({"gw": 2}, set()) == {"gw": 2}


def test_finishing_keeps_the_whole_line_and_trims_only_the_ends(tmp_path):
    # 0.3 s silence, 0.8 s of a voice-like tone that dips between syllables, 0.3 s silence.
    src, out = tmp_path / "in.wav", tmp_path / "out.wav"
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i",
                    "sine=f=180:d=0.8,volume='if(lt(mod(t,0.4),0.3),1,0.01)':eval=frame,"
                    "adelay=300,apad=pad_dur=0.3", "-ar", "24000", str(src)], check=True)
    ffmpeg(src, out, f"{MONSTER},{FINISH}", "-ar", "11025", "-c:a", "pcm_s16le")
    assert 0.6 < duration(out) < 1.0
