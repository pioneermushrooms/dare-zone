# Approved 2026-11-25: Chatterbox cloned off a pitched-down "Ralph", then this chain ("monster").
# Applied to Chatterbox's 24 kHz output.
MONSTER = (
    "asetrate=24000*0.72,aresample=24000,atempo=1.3889,"
    "asoftclip=type=tanh,aexciter=amount=2:drive=6,asoftclip=type=atan,aecho=0.8:0.6:18:0.25,"
    "highpass=f=250,lowpass=f=3600,acompressor=threshold=-18dB:ratio=4:attack=5:release=60,volume=1.6"
)
# Added on export: trim silence at the two ends only (trim the start, reverse, trim the start
# again, reverse back; silenceremove's own stop option cuts at the first dip between words),
# then even out loudness across clips.
_TRIM_START = "silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.03"
FINISH = f"{_TRIM_START},areverse,{_TRIM_START},areverse,loudnorm=I=-16:TP=-1.5"

_EXAGGERATION = {"urgent": 1.0, "hype": 1.0, "smug": 0.9, "calm": 0.6}


def load_phrases() -> dict:
    return json.loads(PHRASES.read_text())


def drop_picks(picks: dict, codes: set) -> dict:
    """Picks without the given phrases: regenerated takes must be heard and picked again."""
    return {c: n for c, n in picks.items() if c not in codes}


def exaggeration(delivery: str) -> float:
    return _EXAGGERATION[delivery]


def too_long(text: str, seconds: float) -> bool:
    """Chatterbox rambles at high exaggeration; a take far longer than the words warrant is junk."""
    words = len(text.split())
    return seconds > (0.6 + 0.28 * words) * 1.5


def duration(path: Path) -> float:
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
                          str(path)], capture_output=True, text=True, check=True)
    return float(out.stdout.strip())


def ffmpeg(src: Path, dst: Path, chain: str, *args: str) -> None:
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(src), "-af", chain, "-ac", "1", *args,
                    str(dst)], check=True)


def _rs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rust_table(table: dict) -> str:
    """The client's voice_table.rs: menus and phrases (code, sound id, team?, menu label)."""
    lines = [
        "// Generated by the voice clip tooling from the zone's phrase table. Do not edit by hand.",
        "",
        "/// A voice-menu level: `code` is the letters after V.",
        "pub struct VoiceMenuDef {",
        "    pub code: &'static str,",
        "    pub label: &'static str,",
        "}",
        "",
        "/// A voice line: `sound` is the chat sound id (128-255) the zone sends with it.",
        "pub struct VoicePhraseDef {",
        "    pub code: &'static str,",
        "    pub sound: u8,",
        "    pub team: bool,",
        "    pub label: &'static str,",
        "}",
        "",
        "pub static MENUS: &[VoiceMenuDef] = &[",
    ]
    lines += [f"    VoiceMenuDef {{ code: {_rs(m['code'])}, label: {_rs(m['label'])} }}," for m in table["menus"]]
    lines += ["];", "", "pub static PHRASES: &[VoicePhraseDef] = &["]
    lines += [f"    VoicePhraseDef {{ code: {_rs(p['code'])}, sound: {p['sound']}, "
              f"team: {'true' if p['scope'] == 'team' else 'false'}, label: {_rs(p['label'])} }},"
              for p in table["phrases"]]
    lines += ["];", ""]
    return "\n".join(lines)
